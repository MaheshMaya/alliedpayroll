import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { formats, transforms } from 'style-dictionary/enums';

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.join(here, 'tokens.json');
const buildDir = path.join(here, 'build');

const EXTENSION = 'com.alliedpayroll';
const OUTPUTS = ['css/tokens.css', 'tailwind/theme.css', 'tailwind/theme-keys.json', 'json/tokens.flat.json'];
// References inside a set are relative to the merged tree ({color.blue.600}, {accent.subtle}),
// so every collection sits at the top level except the ones nothing references.
const NAMESPACED_COLLECTIONS = new Set(['typography']);
const MODE_ATTRIBUTE = { semantic: 'theme' };
// A typography composite becomes one sub-token per CSS property.
const TYPOGRAPHY_PROPERTIES = {
  fontFamily: ['font-family', 'fontFamily'],
  fontWeight: ['font-weight', 'fontWeight'],
  fontSize: ['font-size', 'dimension'],
  lineHeight: ['line-height', 'dimension'],
  letterSpacing: ['letter-spacing', 'dimension'],
};
const HEADER =
  '/* Generated by design-tokens/build.mjs from tokens.json. Edit tokens.json, then run pnpm tokens:build. */\n';

StyleDictionary.registerTransform({
  name: 'name/path-dash',
  type: 'name',
  transform: (token) => token.path.join('-'),
});

const isToken = (node) => typeof node === 'object' && node !== null && '$value' in node;
const isGroup = (node) => typeof node === 'object' && node !== null && !isToken(node);
const meta = (token) => token.$extensions[EXTENSION];

function readCollections(source) {
  const collections = new Map();
  for (const [key, tree] of Object.entries(source)) {
    if (key.startsWith('$')) continue;
    const [name, mode = 'value'] = key.split('/');
    const collection = collections.get(name) ?? { name, defaultMode: mode, modes: new Map() };
    collection.modes.set(mode, tree);
    collections.set(name, collection);
  }
  return collections;
}

function expandTypography(node) {
  const group = {};
  for (const [property, [cssName, type]] of Object.entries(TYPOGRAPHY_PROPERTIES)) {
    if (property in node.$value) group[cssName] = { $type: type, $value: node.$value[property] };
  }
  if (node.$description) group.$description = node.$description;
  return group;
}

function tagTokens(node, collection, mode) {
  if (isToken(node)) {
    if (node.$type === 'typography') return tagTokens(expandTypography(node), collection, mode);
    return { ...node, $extensions: { ...node.$extensions, [EXTENSION]: { collection, mode } } };
  }
  const out = {};
  for (const [key, child] of Object.entries(node)) {
    out[key] = key.startsWith('$') ? child : tagTokens(child, collection, mode);
  }
  return out;
}

function merge(target, addition) {
  for (const [key, value] of Object.entries(addition)) {
    if (isGroup(value) && isGroup(target[key])) merge(target[key], value);
    else target[key] = value;
  }
  return target;
}

function buildTree(collections, modeByCollection) {
  const tree = {};
  for (const collection of collections.values()) {
    const mode = modeByCollection[collection.name];
    const tagged = tagTokens(collection.modes.get(mode), collection.name, mode);
    merge(tree, NAMESPACED_COLLECTIONS.has(collection.name) ? { [collection.name]: tagged } : tagged);
  }
  return tree;
}

function listThemes(collections) {
  const defaults = Object.fromEntries([...collections.values()].map((c) => [c.name, c.defaultMode]));
  const themes = [{ name: 'default', selector: ':root', modes: defaults, collection: null }];
  for (const collection of collections.values()) {
    for (const mode of collection.modes.keys()) {
      if (mode === collection.defaultMode) continue;
      const attribute = MODE_ATTRIBUTE[collection.name] ?? collection.name;
      themes.push({
        name: `${collection.name}-${mode}`,
        selector: `[data-${attribute}="${mode}"]`,
        modes: { ...defaults, [collection.name]: mode },
        collection: collection.name,
      });
    }
  }
  return themes;
}

async function renderTheme(collections, theme) {
  const sd = new StyleDictionary(
    {
      tokens: buildTree(collections, theme.modes),
      usesDtcg: true,
      // Mode blocks reference primitives that only :root declares; SD would warn about that.
      log: { warnings: 'disabled' },
      platforms: {
        css: {
          transforms: [
            'name/path-dash',
            transforms.fontFamilyCss,
            transforms.cubicBezierCss,
            transforms.shadowCssShorthand,
          ],
          files: [
            {
              destination: 'tokens.css',
              format: formats.cssVariables,
              filter: theme.collection ? (token) => meta(token).collection === theme.collection : undefined,
              options: { selector: theme.selector, outputReferences: true, showFileHeader: false },
            },
          ],
        },
      },
    },
    { verbosity: 'silent' },
  );
  const [{ output }] = await sd.formatPlatform('css');
  const { allTokens } = await sd.getPlatformTokens('css');
  return { css: output, tokens: allTokens };
}

function tailwindTheme(tokens) {
  const keys = { color: [], text: [], font: [], 'font-weight': [], spacing: [], radius: [], shadow: [], ease: [] };
  const lines = [];
  const add = (namespace, key, tokenName, suffix = '') => {
    if (!suffix) keys[namespace].push(key);
    lines.push(`  --${namespace}-${key}${suffix}: var(--${tokenName});`);
  };
  for (const token of tokens) {
    const [head, ...rest] = token.path;
    const leaf = rest.join('-');
    if (token.$type === 'color') {
      add('color', head === 'color' ? leaf : token.name, token.name);
    } else if (head === 'space') {
      add('spacing', leaf, token.name);
    } else if (head === 'radius') {
      add('radius', leaf, token.name);
    } else if (token.$type === 'shadow') {
      add('shadow', leaf, token.name);
    } else if (head === 'font' && rest[0] === 'family') {
      add('font', rest[1], token.name);
    } else if (head === 'font' && rest[0] === 'weight') {
      add('font-weight', rest[1], token.name);
    } else if (head === 'easing') {
      add('ease', leaf, token.name);
    } else if (head === 'typography' && rest[0] === 'web') {
      const [, style, property] = rest;
      if (property === 'font-size') add('text', style, token.name);
      else if (property !== 'font-family') add('text', style, token.name, `--${property}`);
    }
  }
  const names = new Set(tokens.map((t) => t.name));
  if (names.has('duration-base')) lines.push('  --default-transition-duration: var(--duration-base);');
  if (names.has('easing-standard')) {
    lines.push('  --default-transition-timing-function: var(--easing-standard);');
  }

  const resets = Object.keys(keys).map((namespace) => `  --${namespace}-*: initial;`);
  const css = [
    HEADER,
    '/* Tailwind default scales are reset so that only token-backed utilities exist. */',
    '@theme inline reference {',
    ...resets,
    '',
    ...lines,
    '}',
    '',
  ].join('\n');
  return { css, keys };
}

function flatJson(defaultTokens, modeThemes) {
  const flat = {};
  for (const token of defaultTokens) {
    const entry = {
      path: token.path.join('/'),
      collection: meta(token).collection,
      type: token.$type,
      value: token.$value,
    };
    if (token.$description) entry.description = token.$description;
    flat[token.name] = entry;
  }
  for (const { theme, tokens } of modeThemes) {
    const mode = theme.modes[theme.collection];
    for (const token of tokens) {
      const entry = flat[token.name];
      if (entry && entry.value !== token.$value) entry.modes = { ...entry.modes, [mode]: token.$value };
    }
  }
  return flat;
}

async function generate() {
  const source = JSON.parse(await readFile(sourcePath, 'utf8'));
  const collections = readCollections(source);
  const [defaultTheme, ...modeThemes] = listThemes(collections);
  const rendered = await renderTheme(collections, defaultTheme);
  const modes = [];
  for (const theme of modeThemes) modes.push({ theme, ...(await renderTheme(collections, theme)) });

  const tailwind = tailwindTheme(rendered.tokens);
  return {
    'css/tokens.css': `${HEADER}\n${[rendered.css, ...modes.map((m) => m.css)].join('\n')}`,
    'tailwind/theme.css': tailwind.css,
    'tailwind/theme-keys.json': `${JSON.stringify(tailwind.keys, null, 2)}\n`,
    'json/tokens.flat.json': `${JSON.stringify(flatJson(rendered.tokens, modes), null, 2)}\n`,
  };
}

async function writeOutputs(dir, outputs) {
  for (const [relative, content] of Object.entries(outputs)) {
    const target = path.join(dir, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, 'utf8');
  }
}

const normalise = (text) => text.replaceAll('\r\n', '\n');

async function check(outputs) {
  const stale = [];
  for (const relative of OUTPUTS) {
    const committed = await readFile(path.join(buildDir, relative), 'utf8').catch(() => null);
    if (committed === null) stale.push(`${relative} (missing)`);
    else if (normalise(committed) !== normalise(outputs[relative])) stale.push(relative);
  }
  if (stale.length > 0) {
    console.error('design-tokens: build/ is out of date. Run pnpm tokens:build and commit the result.');
    for (const entry of stale) console.error(`  ${entry}`);
    process.exit(1);
  }
  console.log(`design-tokens: build/ matches tokens.json (${OUTPUTS.length} files).`);
}

const outputs = await generate();
if (process.argv.includes('--check')) {
  const scratch = await mkdtemp(path.join(tmpdir(), 'allied-tokens-'));
  try {
    await writeOutputs(scratch, outputs);
    await check(outputs);
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
} else {
  await writeOutputs(buildDir, outputs);
  console.log(`design-tokens: wrote ${OUTPUTS.length} files to build/.`);
}
