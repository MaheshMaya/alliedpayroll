import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';
import { formats, transforms } from 'style-dictionary/enums';

const here = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.join(here, 'tokens.json');

const EXTENSION = 'com.alliedpayroll';
const OUTPUTS = [
  'build/css/tokens.css',
  'build/tailwind/theme.css',
  'build/tailwind/theme-keys.json',
  'build/json/tokens.flat.json',
  'flutter/lib/src/tokens.g.dart',
];
// References inside a set are relative to the merged tree ({color.blue.600}, {accent.subtle}),
// so every collection sits at the top level except the ones nothing references.
const NAMESPACED_COLLECTIONS = new Set(['typography']);
const MODE_ATTRIBUTE = { semantic: 'theme' };
// A typography composite becomes one sub-token per CSS property.
const TYPOGRAPHY_PROPERTIES = {
  fontFamily: ['font-family', 'fontFamily'],
  fontWeight: ['font-weight', 'fontWeight'],
  fontSize: ['font-size', 'dimension'],
  lineHeight: ['line-height', 'dimension'],
  letterSpacing: ['letter-spacing', 'dimension'],
};
const HEADER =
  '/* Generated by design-tokens/build.mjs from tokens.json. Edit tokens.json, then run pnpm tokens:build. */\n';
const DART_HEADER =
  '// Generated by design-tokens/build.mjs from tokens.json. Edit tokens.json, then run pnpm tokens:build.\n';

StyleDictionary.registerTransform({
  name: 'name/path-dash',
  type: 'name',
  transform: (token) => token.path.join('-'),
});

const isToken = (node) => typeof node === 'object' && node !== null && '$value' in node;
const isGroup = (node) => typeof node === 'object' && node !== null && !isToken(node);
const meta = (token) => token.$extensions[EXTENSION];

function readCollections(source) {
  const collections = new Map();
  for (const [key, tree] of Object.entries(source)) {
    if (key.startsWith('$')) continue;
    const [name, mode = 'value'] = key.split('/');
    const collection = collections.get(name) ?? { name, defaultMode: mode, modes: new Map() };
    collection.modes.set(mode, tree);
    collections.set(name, collection);
  }
  return collections;
}

function expandTypography(node) {
  const group = {};
  for (const [property, [cssName, type]] of Object.entries(TYPOGRAPHY_PROPERTIES)) {
    if (property in node.$value) group[cssName] = { $type: type, $value: node.$value[property] };
  }
  if (node.$description) group.$description = node.$description;
  return group;
}

function tagTokens(node, collection, mode) {
  if (isToken(node)) {
    if (node.$type === 'typography') return tagTokens(expandTypography(node), collection, mode);
    return { ...node, $extensions: { ...node.$extensions, [EXTENSION]: { collection, mode } } };
  }
  const out = {};
  for (const [key, child] of Object.entries(node)) {
    out[key] = key.startsWith('$') ? child : tagTokens(child, collection, mode);
  }
  return out;
}

function merge(target, addition) {
  for (const [key, value] of Object.entries(addition)) {
    if (isGroup(value) && isGroup(target[key])) merge(target[key], value);
    else target[key] = value;
  }
  return target;
}

function buildTree(collections, modeByCollection) {
  const tree = {};
  for (const collection of collections.values()) {
    const mode = modeByCollection[collection.name];
    const tagged = tagTokens(collection.modes.get(mode), collection.name, mode);
    merge(tree, NAMESPACED_COLLECTIONS.has(collection.name) ? { [collection.name]: tagged } : tagged);
  }
  return tree;
}

function listThemes(collections) {
  const defaults = Object.fromEntries([...collections.values()].map((c) => [c.name, c.defaultMode]));
  const themes = [{ name: 'default', selector: ':root', modes: defaults, collection: null }];
  for (const collection of collections.values()) {
    for (const mode of collection.modes.keys()) {
      if (mode === collection.defaultMode) continue;
      const attribute = MODE_ATTRIBUTE[collection.name] ?? collection.name;
      themes.push({
        name: `${collection.name}-${mode}`,
        selector: `[data-${attribute}="${mode}"]`,
        modes: { ...defaults, [collection.name]: mode },
        collection: collection.name,
      });
    }
  }
  return themes;
}

async function renderTheme(collections, theme) {
  const sd = new StyleDictionary(
    {
      tokens: buildTree(collections, theme.modes),
      usesDtcg: true,
      // Mode blocks reference primitives that only :root declares; SD would warn about that.
      log: { warnings: 'disabled' },
      platforms: {
        css: {
          transforms: [
            'name/path-dash',
            transforms.fontFamilyCss,
            transforms.cubicBezierCss,
            transforms.shadowCssShorthand,
          ],
          files: [
            {
              destination: 'tokens.css',
              format: formats.cssVariables,
              filter: theme.collection ? (token) => meta(token).collection === theme.collection : undefined,
              options: { selector: theme.selector, outputReferences: true, showFileHeader: false },
            },
          ],
        },
      },
    },
    { verbosity: 'silent' },
  );
  const [{ output }] = await sd.formatPlatform('css');
  const { allTokens } = await sd.getPlatformTokens('css');
  return { css: output, tokens: allTokens };
}

function tailwindTheme(tokens) {
  const keys = { color: [], text: [], font: [], 'font-weight': [], spacing: [], radius: [], shadow: [], ease: [] };
  const lines = [];
  const add = (namespace, key, tokenName, suffix = '') => {
    if (!suffix) keys[namespace].push(key);
    lines.push(`  --${namespace}-${key}${suffix}: var(--${tokenName});`);
  };
  for (const token of tokens) {
    const [head, ...rest] = token.path;
    const leaf = rest.join('-');
    if (token.$type === 'color') {
      add('color', head === 'color' ? leaf : token.name, token.name);
    } else if (head === 'space') {
      add('spacing', leaf, token.name);
    } else if (head === 'radius') {
      add('radius', leaf, token.name);
    } else if (token.$type === 'shadow') {
      add('shadow', leaf, token.name);
    } else if (head === 'font' && rest[0] === 'family') {
      add('font', rest[1], token.name);
    } else if (head === 'font' && rest[0] === 'weight') {
      add('font-weight', rest[1], token.name);
    } else if (head === 'easing') {
      add('ease', leaf, token.name);
    } else if (head === 'typography' && rest[0] === 'web') {
      const [, style, property] = rest;
      if (property === 'font-size') add('text', style, token.name);
      else if (property !== 'font-family') add('text', style, token.name, `--${property}`);
    }
  }
  const names = new Set(tokens.map((t) => t.name));
  if (names.has('duration-base')) lines.push('  --default-transition-duration: var(--duration-base);');
  if (names.has('easing-standard')) {
    lines.push('  --default-transition-timing-function: var(--easing-standard);');
  }

  const resets = Object.keys(keys).map((namespace) => `  --${namespace}-*: initial;`);
  const css = [
    HEADER,
    '/* Tailwind default scales are reset so that only token-backed utilities exist. */',
    '@theme inline reference {',
    ...resets,
    '',
    ...lines,
    '}',
    '',
  ].join('\n');
  return { css, keys };
}

function flatJson(defaultTokens, modeThemes) {
  const flat = {};
  for (const token of defaultTokens) {
    const entry = {
      path: token.path.join('/'),
      collection: meta(token).collection,
      type: token.$type,
      value: token.$value,
    };
    if (token.$description) entry.description = token.$description;
    flat[token.name] = entry;
  }
  for (const { theme, tokens } of modeThemes) {
    const mode = theme.modes[theme.collection];
    for (const token of tokens) {
      const entry = flat[token.name];
      if (entry && entry.value !== token.$value) entry.modes = { ...entry.modes, [mode]: token.$value };
    }
  }
  return flat;
}

// ---- Flutter -------------------------------------------------------------------------------

const dartIdentifier = (segments) =>
  segments
    .map((segment) => segment.replace(/^2xl$/, 'xxl').replace(/^(\d)/, 's$1'))
    .map((segment, index) => (index === 0 ? segment : segment[0].toUpperCase() + segment.slice(1)))
    .join('');

function dartColor(hex) {
  const digits = hex.replace('#', '').toUpperCase();
  const rgb = digits.slice(0, 6);
  const alpha = digits.slice(6, 8) || 'FF';
  return `Color(0x${alpha}${rgb})`;
}

const px = (value) => Number.parseFloat(String(value).replace('px', ''));
const dartNumber = (value) => (Number.isInteger(value) ? String(value) : String(Number(value.toFixed(4))));
const dartString = (value) => `'${value.replaceAll("'", "\\'")}'`;

function dartShadow(value) {
  const parts = value.match(/(-?[\d.]+)px (-?[\d.]+)px (-?[\d.]+)px (-?[\d.]+)px (#[0-9A-Fa-f]+)/);
  if (!parts) throw new Error(`Unsupported shadow value: ${value}`);
  const [, x, y, blur, spread, color] = parts;
  return [
    'BoxShadow(',
    `offset: Offset(${dartNumber(px(x))}, ${dartNumber(px(y))}), `,
    `blurRadius: ${dartNumber(px(blur))}, `,
    px(spread) === 0 ? '' : `spreadRadius: ${dartNumber(px(spread))}, `,
    `color: ${dartColor(color)})`,
  ].join('');
}

function fontFamilies(value) {
  return value
    .split(',')
    .map((name) => name.trim().replace(/^'|'$/g, ''))
    .filter((name) => !['system-ui', 'sans-serif', 'monospace', 'ui-monospace'].includes(name));
}

function themeExtension(className, fields, instances, doc) {
  const names = fields.map((field) => field.name);
  const lines = [doc, `class ${className} extends ThemeExtension<${className}> {`];
  lines.push(`  const ${className}({`);
  for (const name of names) lines.push(`    required this.${name},`);
  lines.push('  });', '');
  for (const field of fields) {
    if (field.doc) lines.push(`  /// ${field.doc}`);
    lines.push(`  final Color ${field.name};`);
  }
  for (const [instanceName, values, instanceDoc] of instances) {
    lines.push('', `  /// ${instanceDoc}`, `  static const ${className} ${instanceName} = ${className}(`);
    for (const name of names) lines.push(`    ${name}: ${values[name]},`);
    lines.push('  );');
  }
  lines.push('', '  @override', `  ${className} copyWith({`);
  for (const name of names) lines.push(`    Color? ${name},`);
  lines.push('  }) {', `    return ${className}(`);
  for (const name of names) lines.push(`      ${name}: ${name} ?? this.${name},`);
  lines.push('    );', '  }', '', '  @override', `  ${className} lerp(${className}? other, double t) {`);
  lines.push('    if (other == null) return this;', `    return ${className}(`);
  for (const name of names) lines.push(`      ${name}: Color.lerp(${name}, other.${name}, t)!,`);
  lines.push('    );', '  }', '}');
  return lines.join('\n');
}

function constClass(className, doc, entries) {
  return [
    doc,
    `abstract final class ${className} {`,
    ...entries.map(
      ([name, type, value, entryDoc]) =>
        `${entryDoc ? `  /// ${entryDoc}\n` : ''}  static const ${type} ${name} = ${value};`,
    ),
    '}',
  ].join('\n');
}

function flutterDart(defaultTokens, modeThemes) {
  const byPath = new Map(defaultTokens.map((token) => [token.path.join('/'), token]));
  const modeValue = (collection, mode, tokenPath) => {
    const theme = modeThemes.find(
      (m) => m.theme.collection === collection && m.theme.modes[collection] === mode,
    );
    return theme?.tokens.find((token) => token.path.join('/') === tokenPath)?.$value;
  };
  const pick = (predicate) => defaultTokens.filter(predicate);
  const valueIn = (collection, defaultMode, mode, token) =>
    mode === defaultMode ? token.$value : (modeValue(collection, mode, token.path.join('/')) ?? token.$value);

  const semanticColors = pick((t) => meta(t).collection === 'semantic' && t.$type === 'color');
  const colorFields = semanticColors.map((t) => ({ name: dartIdentifier(t.path.slice(1)), doc: t.$description }));
  const colorValues = (mode) =>
    Object.fromEntries(
      semanticColors.map((t) => [dartIdentifier(t.path.slice(1)), dartColor(valueIn('semantic', 'light', mode, t))]),
    );
  const colors = themeExtension(
    'AlliedColors',
    colorFields,
    [
      ['light', colorValues('light'), 'The light theme.'],
      ['dark', colorValues('dark'), 'The dark theme.'],
    ],
    '/// Semantic colours. Read them with `Theme.of(context).extension<AlliedColors>()`.',
  );

  const brandTokens = pick((t) => meta(t).collection === 'brand');
  const brandFields = brandTokens.map((t) => ({ name: dartIdentifier(t.path), doc: t.$description }));
  const brandValues = (mode) =>
    Object.fromEntries(
      brandTokens.map((t) => [dartIdentifier(t.path), dartColor(valueIn('brand', 'default', mode, t))]),
    );
  const brand = themeExtension(
    'AlliedBrand',
    brandFields,
    [
      ['defaultBrand', brandValues('default'), 'The product accent, used when a tenant has no brand of its own.'],
      ['teal', brandValues('teal'), 'Tenant accent preset.'],
      ['amber', brandValues('amber'), 'Tenant accent preset.'],
      ['plum', brandValues('plum'), 'Tenant accent preset.'],
    ],
    '/// The tenant accent. One preset is chosen from bootstrap branding; custom accents come as a copy.',
  );

  const dimension = (prefix) =>
    pick((t) => t.path[0] === prefix && t.$type === 'dimension').map((t) => [
      dartIdentifier(t.path.slice(1)),
      'double',
      dartNumber(px(t.$value)),
      t.$description,
    ]);
  const space = constClass('AlliedSpace', '/// The spacing scale, in logical pixels.', dimension('space'));
  const radius = constClass('AlliedRadius', '/// Corner radii, in logical pixels.', dimension('radius'));

  const durations = pick((t) => t.$type === 'duration').map((t) => [
    dartIdentifier(t.path.slice(1)),
    'Duration',
    `Duration(milliseconds: ${Number.parseInt(t.$value, 10)})`,
    t.$description,
  ]);
  const duration = constClass('AlliedDuration', '/// Motion durations.', durations);

  const curves = pick((t) => t.$type === 'cubicBezier').map((t) => {
    const [x1, y1, x2, y2] = String(t.$value).match(/[\d.]+/g).map(Number);
    return [dartIdentifier(t.path.slice(1)), 'Cubic', `Cubic(${x1}, ${y1}, ${x2}, ${y2})`, t.$description];
  });
  const easing = constClass('AlliedCurves', '/// Motion curves.', curves);

  const families = pick((t) => t.path[0] === 'font' && t.path[1] === 'family').map((t) => {
    const [primary, ...fallback] = fontFamilies(t.$value);
    return [
      dartIdentifier(t.path.slice(2)),
      'FontFamily',
      `FontFamily(${dartString(primary)}, [${fallback.map(dartString).join(', ')}])`,
      t.$description,
    ];
  });
  const fontFamily = [
    '/// A font family with its fallbacks, for [TextStyle.fontFamily] and [TextStyle.fontFamilyFallback].',
    'class FontFamily {',
    '  const FontFamily(this.name, this.fallback);',
    '',
    '  final String name;',
    '  final List<String> fallback;',
    '}',
    '',
    constClass('AlliedFontFamily', '/// Font families. Indic scripts get a Noto family first.', families),
  ].join('\n');

  const weights = pick((t) => t.$type === 'fontWeight' && t.path[0] === 'font').map((t) => [
    dartIdentifier(t.path.slice(2)),
    'FontWeight',
    `FontWeight.w${t.$value}`,
    t.$description,
  ]);
  const fontWeight = constClass('AlliedFontWeight', '/// Font weights.', weights);

  const textStyleNames = new Map();
  for (const t of pick((t) => t.path[0] === 'typography' && ['mobile', 'kiosk'].includes(t.path[1]))) {
    textStyleNames.set(`${t.path[1]}/${t.path[2]}`, t.path.slice(1, 3));
  }
  const textStyles = [...textStyleNames.entries()].map(([key, segments]) => {
    const prop = (name) => byPath.get(`typography/${key}/${name}`)?.$value;
    const size = px(prop('font-size'));
    const lineHeight = px(prop('line-height'));
    const spacing = String(prop('letter-spacing'));
    const letterSpacing = spacing.endsWith('em') ? Number.parseFloat(spacing) * size : px(spacing);
    const [primary, ...fallback] = fontFamilies(prop('font-family'));
    const value = [
      'TextStyle(',
      `    fontFamily: ${dartString(primary)},`,
      `    fontFamilyFallback: [${fallback.map(dartString).join(', ')}],`,
      `    fontSize: ${dartNumber(size)},`,
      `    height: ${dartNumber(lineHeight / size)},`,
      `    fontWeight: FontWeight.w${prop('font-weight')},`,
      `    letterSpacing: ${dartNumber(letterSpacing)},`,
      '  )',
    ].join('\n');
    return [dartIdentifier(segments), 'TextStyle', value];
  });
  const indic = byPath.get('typography/indicLineHeightMultiplier');
  if (indic) {
    textStyles.push([
      'indicLineHeightMultiplier',
      'double',
      dartNumber(Number(indic.$value)),
      'Multiply [TextStyle.height] by this for Devanagari, Tamil and other Indic scripts.',
    ]);
  }
  const typography = constClass('AlliedTextStyles', '/// Mobile and kiosk text styles. Web styles stay in CSS.', textStyles);

  const shadows = pick((t) => t.$type === 'shadow').map((t) => [
    dartIdentifier(t.path.slice(1)),
    t.$value,
    modeValue('semantic', 'dark', t.path.join('/')) ?? t.$value,
  ]);
  const shadow = [
    '/// Elevation shadows per theme.',
    'abstract final class AlliedShadow {',
    ...shadows.flatMap(([name, light, dark]) => [
      `  static const List<BoxShadow> ${name}Light = [${dartShadow(light)}];`,
      `  static const List<BoxShadow> ${name}Dark = [${dartShadow(dark)}];`,
    ]),
    '}',
  ].join('\n');

  const densityTokens = pick((t) => meta(t).collection === 'density');
  const densityFields = densityTokens.map((t) => dartIdentifier(t.path));
  const densityInstance = (mode) =>
    densityTokens.map(
      (t) => `    ${dartIdentifier(t.path)}: ${dartNumber(px(valueIn('density', 'comfortable', mode, t)))},`,
    );
  const density = [
    '/// Control and table sizes for the two densities. Phones use comfortable; tablets may use compact.',
    'class AlliedDensity {',
    '  const AlliedDensity({',
    ...densityFields.map((name) => `    required this.${name},`),
    '  });',
    '',
    ...densityFields.map((name) => `  final double ${name};`),
    '',
    '  static const AlliedDensity comfortable = AlliedDensity(',
    ...densityInstance('comfortable'),
    '  );',
    '',
    '  static const AlliedDensity compact = AlliedDensity(',
    ...densityInstance('compact'),
    '  );',
    '}',
  ].join('\n');

  const sections = [colors, brand, space, radius, duration, easing, fontFamily, fontWeight, typography, shadow, density];
  return [
    DART_HEADER,
    '// dart format off',
    '// ignore_for_file: public_member_api_docs, lines_longer_than_80_chars',
    '',
    "import 'package:flutter/material.dart';",
    '',
    sections.join('\n\n'),
    '',
  ].join('\n');
}

async function generate() {
  const source = JSON.parse(await readFile(sourcePath, 'utf8'));
  const collections = readCollections(source);
  const [defaultTheme, ...modeThemes] = listThemes(collections);
  const rendered = await renderTheme(collections, defaultTheme);
  const modes = [];
  for (const theme of modeThemes) modes.push({ theme, ...(await renderTheme(collections, theme)) });

  const tailwind = tailwindTheme(rendered.tokens);
  return {
    'build/css/tokens.css': `${HEADER}\n${[rendered.css, ...modes.map((m) => m.css)].join('\n')}`,
    'build/tailwind/theme.css': tailwind.css,
    'build/tailwind/theme-keys.json': `${JSON.stringify(tailwind.keys, null, 2)}\n`,
    'build/json/tokens.flat.json': `${JSON.stringify(flatJson(rendered.tokens, modes), null, 2)}\n`,
    'flutter/lib/src/tokens.g.dart': flutterDart(rendered.tokens, modes),
  };
}

async function writeOutputs(dir, outputs) {
  for (const [relative, content] of Object.entries(outputs)) {
    const target = path.join(dir, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content, 'utf8');
  }
}

const normalise = (text) => text.replaceAll('\r\n', '\n');

async function check(outputs) {
  const stale = [];
  for (const relative of OUTPUTS) {
    const committed = await readFile(path.join(here, relative), 'utf8').catch(() => null);
    if (committed === null) stale.push(`${relative} (missing)`);
    else if (normalise(committed) !== normalise(outputs[relative])) stale.push(relative);
  }
  if (stale.length > 0) {
    console.error('design-tokens: generated files are out of date. Run pnpm tokens:build and commit the result.');
    for (const entry of stale) console.error(`  ${entry}`);
    process.exit(1);
  }
  console.log(`design-tokens: generated files match tokens.json (${OUTPUTS.length} files).`);
}

const outputs = await generate();
if (process.argv.includes('--check')) {
  const scratch = await mkdtemp(path.join(tmpdir(), 'allied-tokens-'));
  try {
    await writeOutputs(scratch, outputs);
    await check(outputs);
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
} else {
  await writeOutputs(here, outputs);
  console.log(`design-tokens: wrote ${OUTPUTS.length} files.`);
}
